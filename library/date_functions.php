function dateformat($strtime = '', $with_dow = false)
{
    // without an argument, display current date
    if (!$strtime) {
        $carbon = Carbon::now();
    } else {
        // Parse the input - could be timestamp or date string
        $carbon = DateHelper::parse($strtime);
    }

    // Get localized day of week
    $dow = xl($carbon->format('l'));

    // Get localized month name
    $monthName = $carbon->format('F');
    $nom = xl($monthName);

    // Date string format based on language
    $languageTitle = getLanguageTitle($_SESSION['language_choice']);
    switch ($languageTitle) {
        // standard english first
        case getLanguageTitle(1):
            $dt = $carbon->format("F j, Y");
            if ($with_dow) {
                $dt = "$dow, $dt";
            }
            break;
        case "Swedish":
            $dt = $carbon->format("Y") . " $nom " . $carbon->format("d");
            if ($with_dow) {
                $dt = "$dow $dt";
            }
            break;
        case "Spanish":
        case "Spanish (Spain)":
        case "Spanish (Latin American)":
            $dt = $carbon->format("d") . " $nom " . $carbon->format("Y");
            if ($with_dow) {
                $dt = "$dow $dt";
            }
            break;
        case "German":
            $dt = $carbon->format("d") . " $nom " . $carbon->format("Y");
            if ($with_dow) {
                $dt = "$dow $dt";
            }
            break;
        case "Dutch":
            $dt = $carbon->format("d") . " $nom " . $carbon->format("Y");
            if ($with_dow) {
                $dt = "$dow $dt";
            }
            break;
            // hebrew (israel) , display english NOT jewish calendar
        case "Hebrew":
            $dt = $carbon->format("d") . " $nom " . $carbon->format("Y");
            if ($with_dow) {
                $dt = "$dow, $dt";
            }
            break;
            // default case
        default:
            $dt = "$nom " . $carbon->format("d") . ", " . $carbon->format("Y");
            if ($with_dow) {
                $dt = "$dow, $dt";
            }
    }

    return $dt;
}
